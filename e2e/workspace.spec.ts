import { test, expect } from '@playwright/test';

test('mobile planner, backtest report and backup restore', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/?mode=demo');
  await expect(page.getByRole('heading', { name: 'Know your markets.' })).toBeVisible();
  await page.getByRole('button', { name: 'Strategy planner', exact: true }).click();
  await page.getByLabel('Plan name', { exact: true }).fill('Browser test plan');
  await page.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(page.getByText('Strategy checklist saved locally.')).toBeVisible();
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  const backtest = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Crypto strategy backtest', exact: true }) });
  await backtest.getByLabel('Saved crypto plan').selectOption({ label: 'Browser test plan · BTC/USDT · 1h · long' });
  await backtest.getByRole('button', { name: 'Run backtest' }).click();
  await expect(backtest.getByText(/Results for Browser test plan/)).toBeVisible();
  const reportDownload = page.waitForEvent('download');
  await backtest.getByRole('button', { name: 'Download results (JSON)' }).click();
  const report = JSON.parse(await (await (await reportDownload).createReadStream()).toArray().then((chunks) => Buffer.concat(chunks).toString()));
  expect(report.format).toBe('TradingNinjaPro.backtest.v1');
  expect(report.dataMode).toBe('historical-demo-shifted');
  expect(report.simulation.name).toBe('Browser test plan');
  expect(report.simulation.bars).toBeGreaterThan(20);
  expect(report.summary.simulatedCloses).toBe(report.simulation.trades.length);
  expect(report.assumptions).toContain('not a prediction');
  const backupDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Backup', exact: true }).click();
  const backup = await (await backupDownload).createReadStream();
  const bytes = Buffer.concat(await backup.toArray());
  expect(JSON.parse(bytes.toString()).workspace.plans[0].name).toBe('Browser test plan');
  // Bad input cannot overwrite the account; cancelling a valid restore is also non-destructive.
  await page.getByLabel('Restore local account backup').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{') });
  await expect(page.getByText(/JSON/).last()).toBeVisible();
  const replacement = JSON.parse(bytes.toString());
  replacement.workspace.plans[0].name = 'Restored plan';
  const replacementBytes = Buffer.from(JSON.stringify(replacement));
  let confirmation = '';
  page.once('dialog', async (dialog) => { confirmation = dialog.message(); await dialog.dismiss(); });
  await page.getByLabel('Restore local account backup').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: replacementBytes });
  await expect.poll(() => confirmation).toContain('plans');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Know your markets.' })).toBeVisible();
  await expect(backtest.getByLabel('Saved crypto plan').locator('option', { hasText: 'Browser test plan' })).toHaveCount(1);
  page.once('dialog', (dialog) => dialog.accept());
  await Promise.all([page.waitForEvent('load'), page.getByLabel('Restore local account backup').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: replacementBytes })]);
  await expect(page.getByRole('heading', { name: 'Know your markets.' })).toBeVisible();
  await expect(backtest.getByLabel('Saved crypto plan').locator('option', { hasText: 'Restored plan' })).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
